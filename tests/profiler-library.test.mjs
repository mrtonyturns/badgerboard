// tests/profiler-library.test.mjs — the v2.0 Profiler library: a shelf of short
// paper documents instead of a table (owner request, Nov 2026).
//
//   1. library.js pure helpers: grouping by candidate (newest on top, older
//      versions behind), search, the search threshold, sourcing label, quota line
//   2. the page wiring: tiles not a table, one quiet quota line, New profile
//      dialog keeps the quota checks, Bulk only where the plan allows it,
//      versions reachable from the tile menu AND inside the reader
import { readFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const src  = (p) => readFileSync(join(ROOT, p), 'utf8')

let pass = 0, fail = 0
const t = (name, cond) => { cond ? pass++ : fail++; console.log(`${cond ? '  ✓' : '  ✗ FAIL'} ${name}`) }
const eq = (name, got, want) => {
  const ok = JSON.stringify(got) === JSON.stringify(want)
  if (!ok) console.log(`      got ${JSON.stringify(got)} · want ${JSON.stringify(want)}`)
  t(name, ok)
}

// library.js is import-free plain ESM; load it as a data: module so the test
// does not depend on how Node classifies a .js file in this package.
const libSrc = src('src/pages/profiler/library.js')
t('library.js stays import-free (pure)', !/^\s*import\s/m.test(libSrc))
const L = await import('data:text/javascript;base64,' + Buffer.from(libSrc, 'utf8').toString('base64'))

// ═══ 1 — pure helpers ═════════════════════════════════════════════════════════
console.log('1 — grouping, search, labels, quota')
{
  const rows = [
    { id: 'a1', candidateId: 'A', generatedAt: '2026-07-02T10:00:00Z', name: 'Ann Able', office: 'State Senate', district: 'SD 29' },
    { id: 'b1', candidateId: 'B', generatedAt: '2026-11-01T10:00:00Z', name: 'Bob Burr', office: '', district: '' },
    { id: 'a3', candidateId: 'A', generatedAt: '2026-11-12T10:00:00Z', name: 'Ann Able', office: 'State Senate', district: 'SD 29' },
    { id: 'x1', candidateId: null, generatedAt: '2026-10-01T10:00:00Z', name: 'Unknown candidate', office: '', district: '' },
    { id: 'a2', candidateId: 'A', generatedAt: '2026-09-20T10:00:00Z', name: 'Ann Able', office: 'State Senate', district: 'SD 29' },
    { id: 'y1', candidateId: null, generatedAt: '2026-08-01T10:00:00Z', name: 'Unknown candidate', office: '', district: '' },
  ]
  const g = L.groupProfiles(rows)
  eq('one tile per candidate, unlinked profiles stand alone', g.map(x => x.key), ['c:A', 'c:B', 'd:x1', 'd:y1'])
  eq('a tile shows its NEWEST version', g[0].latest.id, 'a3')
  eq('older versions stay with it, newest first', g[0].versions.map(v => v.id), ['a3', 'a2', 'a1'])
  eq('a single profile is a one-version group', g[1].versions.length, 1)
  t('input order does not matter', JSON.stringify(L.groupProfiles([...rows].reverse())) === JSON.stringify(g))
  eq('empty / missing input is an empty shelf', [L.groupProfiles([]).length, L.groupProfiles(null).length], [0, 0])
  t('a row with no date sorts last, not first',
    L.groupProfiles([{ id: 'n', candidateId: 'N', generatedAt: null }, { id: 'm', candidateId: 'M', generatedAt: '2026-01-01' }])[0].key === 'c:M')

  eq('search by name', L.filterGroups(g, 'bob').map(x => x.key), ['c:B'])
  eq('search by office, case-insensitive', L.filterGroups(g, 'STATE sen').map(x => x.key), ['c:A'])
  eq('search by district', L.filterGroups(g, 'sd 29').map(x => x.key), ['c:A'])
  eq('blank query keeps everything', L.filterGroups(g, '  ').length, 4)

  t('no search box for a short shelf', !L.showSearch(8))
  t('a search box past ~8 profiles', L.showSearch(9))

  eq('sourced label', L.sourcedLabel({ hasRatio: true, good: 14, weak: 23 }), '14 of 37 sourced')
  eq('too few tagged claims → no label (no dead data)', L.sourcedLabel({ hasRatio: false, good: 1, weak: 1 }), '')

  eq('quota line', L.quotaParts({ unlimited: false, left: 6, limit: 6, resetLabel: 'resets Dec 1' }),
    ['6 of 6 profiles left this month', 'resets Dec 1'])
  eq('quota line, singular', L.quotaParts({ unlimited: false, left: 1, limit: 1, resetLabel: 'resets Dec 1' })[0],
    '1 of 1 profile left this month')
  eq('quota line, used up', L.quotaParts({ unlimited: false, left: 0, limit: 6, resetLabel: 'resets Dec 1' })[0],
    'No profiles left this month')
  eq('banked credits are mentioned, not hidden', L.quotaParts({ unlimited: false, left: 8, limit: 8, resetLabel: 'r', banked: 2 })[2],
    'includes 2 banked credits')
  eq('unlimited accounts say so, with what they generated',
    L.quotaParts({ unlimited: true, used: 3 }), ['Unlimited on your account', '3 generated by you this month'])
}

// ═══ 2 — page wiring ══════════════════════════════════════════════════════════
console.log('2 — the library is tiles, the plan is one line, generating is a dialog')
{
  const s = src('src/pages/Dossiers.jsx')
  const tiles = src('src/pages/profiler/ProfileTiles.jsx')

  t('rows are grouped by candidate', /groupProfiles\(rows\)/.test(s))
  t('each group renders as a DocTile', /<DocTile\b/.test(s))
  t('clicking a tile opens the existing reader', /onOpen=\{id => openDossier\(id\)\}/.test(s))
  t('the old table, generate row and stat strip are gone',
    !/className="pf-row"/.test(s) && !/className="pf-genrow"/.test(s) && !/<ProfilerStatStrip/.test(s))
  t('the tile looks like a paper document: red eyebrow, heavy name, page lines',
    /Political profile/.test(tiles) && /text-brand-red/.test(tiles) && /font-extrabold/.test(tiles) && /PAGE_LINES\.map/.test(tiles))
  t('the footer carries date, sourcing, to-verify and the WEEKLY tag',
    /\{r\.date\}/.test(tiles) && /sourcedLabel\(r\)/.test(tiles) && /r\.flags\.verifyLabel/.test(tiles) && />WEEKLY</.test(tiles))
  t('several versions get the stacked-paper edge and a count',
    /stacked && \(/.test(tiles) && /\{versions\} versions/.test(tiles))
  t('older versions are reachable from the tile menu', /Earlier versions/.test(tiles) && /older\.map\(/.test(tiles))
  t('…and inside the reader', /<VersionSwitcher\b/.test(s) && /headerExtra=\{selectedVersions\.length > 1/.test(s))
  t('the tile menu closes on Escape through the shared hook, without a scroll lock',
    /useDialog\(onClose, \{ locked: false \}\)/.test(tiles))

  t('"New profile" is the primary action', /icon=\{Plus\}[\s\S]{0,200}?>New profile</.test(s))
  t('Bulk generate only where the plan allows it', /\{canBulk \? \(\s*<Button[\s\S]{0,160}?>Bulk generate<\/Button>\s*\) : null\}/.test(s))
  t('the dialog keeps the candidate picker and research context',
    /<SearchableSelect[\s\S]{0,400}?placeholder="Choose a candidate"/.test(s) && /id="pf-context"/.test(s))
  t('Generate still goes through the disclaimer + quota path (handleGenerate)',
    /onClick=\{\(\) => \{ setNewOpen\(false\); handleGenerate\(\) \}\}/.test(s))
  t('Generate is disabled with no profiles left', /disabled=\{!candidateId \|\| generating \|\| outOfProfiles\}/.test(s))
  t('outOfProfiles is the same rule as before (!unlimited && left === 0)', /const outOfProfiles = !unlimited && left === 0/.test(s))
  t('adding someone new still creates the candidate and runs', /onClick=\{handleCreateAndRun\}/.test(s))
  t('the District Dashboard ?newname= deep link opens the dialog in create mode',
    /setNewMode\('create'\)\s*\n\s*setNewOpen\(true\)/.test(s))
  t('?candidate= with no profile yet opens the dialog preselected',
    /if \(!dossiers\.some\(d => d\.candidate_id === initCandidateId\)\) \{ setNewMode\('pick'\); setNewOpen\(true\) \}/.test(s))
  t('the quota is one quiet line with an Add more link (web only)',
    /quota\.join\(' · '\)/.test(s) && /<WebOnlyCta>[\s\S]{0,300}?'Add more'/.test(s))
  t('a friendly empty state with New profile', /<EmptyState[\s\S]{0,500}?title="No profiles yet"[\s\S]{0,400}?>New profile</.test(s))
  t('phone: two columns of tiles below 520px', /max-\[520px\]:grid-cols-2/.test(s))
  const code = s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/.*$/gm, '')
  t('the library still has no <h1> of its own (Layout owns it)', !/<h1/.test(code))
}

console.log(`\n${pass} passed, ${fail} failed`)
process.exit(fail ? 1 : 0)
