// src/pages/profiler/library.js — pure helpers for the Profiler library shelf.
//
// The library used to be a table with one row per generated profile, so a
// candidate profiled three times took three rows. It is now a shelf of short
// paper documents: ONE tile per candidate, showing the newest profile, with the
// older versions stacked behind it. Everything here is pure (no React, no
// imports) so tests/profiler-library.test.mjs can exercise it directly.

const ts = (iso) => {
  const t = iso ? new Date(iso).getTime() : NaN
  return Number.isFinite(t) ? t : -Infinity
}

/**
 * One group per candidate, newest version first, groups ordered by their
 * newest version. A profile with no candidate link stands on its own.
 *   rows: [{ id, candidateId, generatedAt, ... }]
 *   → [{ key, latest, versions: [latest, older…] }]
 */
export function groupProfiles(rows) {
  const sorted = [...(rows || [])].filter(Boolean)
    .sort((a, b) => ts(b.generatedAt) - ts(a.generatedAt))
  const groups = new Map()
  for (const r of sorted) {
    const key = r.candidateId ? `c:${r.candidateId}` : `d:${r.id}`
    const g = groups.get(key)
    if (g) g.versions.push(r)
    else groups.set(key, { key, latest: r, versions: [r] })
  }
  return [...groups.values()]
}

/** Search over a group's newest name/office/district. Empty query keeps all. */
export function filterGroups(groups, query) {
  const q = String(query || '').trim().toLowerCase()
  if (!q) return groups || []
  return (groups || []).filter(({ latest: r }) =>
    [r.name, r.office, r.district].some(v => String(v || '').toLowerCase().includes(q)))
}

/** The search box only earns its place once the shelf is longer than this. */
export const SEARCH_THRESHOLD = 8
export const showSearch = (groupCount) => groupCount > SEARCH_THRESHOLD

/** "14 of 37 sourced" — or '' when there are too few tagged claims to say. */
export function sourcedLabel(row) {
  return row && row.hasRatio ? `${row.good} of ${row.good + row.weak} sourced` : ''
}

/**
 * The quota as one quiet line of parts (the page joins them with " · " and
 * appends the Add-more link itself):
 *   ['6 of 6 profiles left this month', 'resets Dec 1']
 *   ['No profiles left this month', 'resets Dec 1']
 *   ['Unlimited on your account', '3 generated by you this month']
 */
export function quotaParts({ unlimited, left, limit, resetLabel, used = 0, banked = 0 }) {
  if (unlimited) {
    return ['Unlimited on your account', used ? `${used} generated by you this month` : 'none generated by you this month']
  }
  const parts = [left > 0
    ? `${left} of ${limit} profile${limit === 1 ? '' : 's'} left this month`
    : 'No profiles left this month']
  if (resetLabel) parts.push(resetLabel)
  if (banked > 0) parts.push(`includes ${banked} banked credit${banked === 1 ? '' : 's'}`)
  return parts
}
