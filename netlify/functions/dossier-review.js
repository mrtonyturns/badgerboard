// Netlify Function: dossier-review
// Handles two actions:
//   1. acknowledge  — records that the user acknowledged the Research Use Disclaimer
//   2. save_review  — saves a user's Confirmed/Rejected/Needs Research annotation
//   3. get_ack      — returns the user's current acknowledgment status
//   4. get_reviews  — returns all claim reviews for a dossier
//
// Requires a valid Supabase JWT in the Authorization header.

const SUPABASE_URL          = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL
const SUPABASE_SERVICE_KEY  = process.env.SUPABASE_SERVICE_ROLE_KEY
const RESEND_API_KEY        = process.env.RESEND_API_KEY
const DISCLAIMER_VERSION    = '1.0'

import { corsHeaders } from './_config.js'

// ─── Verify Supabase JWT ──────────────────────────────────────────────────────
async function verifyUser(authHeader) {
  if (!authHeader?.startsWith('Bearer ')) return null
  const token = authHeader.slice(7)
  const res = await fetch(`${SUPABASE_URL}/auth/v1/user`, {
    headers: {
      apikey: SUPABASE_SERVICE_KEY,
      Authorization: `Bearer ${token}`,
    },
  })
  if (!res.ok) return null
  return await res.json()
}

// ─── Supabase REST helper ─────────────────────────────────────────────────────
async function supabaseQuery(path, method = 'GET', body = null, params = '') {
  const url = `${SUPABASE_URL}/rest/v1/${path}${params}`
  const opts = {
    method,
    headers: {
      apikey: SUPABASE_SERVICE_KEY,
      Authorization: `Bearer ${SUPABASE_SERVICE_KEY}`,
      'Content-Type': 'application/json',
      Prefer: method === 'POST' ? 'return=representation' : 'return=minimal',
    },
  }
  if (body) opts.body = JSON.stringify(body)
  const res = await fetch(url, opts)
  const text = await res.text()
  let data = null
  try { data = JSON.parse(text) } catch {}
  return { ok: res.ok, status: res.status, data }
}

