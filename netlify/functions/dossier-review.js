// ─── Handler ──────────────────────────────────────────────────────────────────
export const handler = async (event) => {
  const headers = corsHeaders(event.headers?.origin || event.headers?.Origin)

  if (event.httpMethod === 'OPTIONS') return { statusCode: 200, headers, body: '' }
  if (event.httpMethod !== 'POST') {
    return { statusCode: 405, headers, body: JSON.stringify({ error: 'Method not allowed' }) }
  }

  // Verify auth
  const user = await verifyUser(event.headers?.authorization || event.headers?.Authorization)
  if (!user) {
    return { statusCode: 401, headers, body: JSON.stringify({ error: 'Unauthorized' }) }
  }

  let body
  try { body = JSON.parse(event.body) } catch {
    return { statusCode: 400, headers, body: JSON.stringify({ error: 'Invalid JSON' }) }
  }

  const { action } = body

  // ── acknowledge ─────────────────────────────────────────────────────────────
  if (action === 'acknowledge') {
    const now = new Date().toISOString()

    // Mark previous acknowledgments as not current
    await supabaseQuery(
      `dossier_acknowledgments?user_id=eq.${user.id}&is_current=eq.true`,
      'PATCH',
      { is_current: false }
    )

    // Insert new acknowledgment
    const { ok, data } = await supabaseQuery('dossier_acknowledgments', 'POST', {
      user_id:             user.id,
      user_email:          user.email,
      disclaimer_version:  DISCLAIMER_VERSION,
      acknowledged_at:     now,
      ip_address:          event.headers?.['x-forwarded-for']?.split(',')[0]?.trim() || null,
      user_agent:          event.headers?.['user-agent'] || null,
      is_current:          true,
    })

    if (!ok) {
      return { statusCode: 500, headers, body: JSON.stringify({ error: 'Failed to record acknowledgment' }) }
    }

    // Send confirmation email (non-blocking)
    sendAckEmail(user.email, now).catch(() => {})

    return {
      statusCode: 200,
      headers,
      body: JSON.stringify({
        ok: true,
        acknowledged_at: now,
        disclaimer_version: DISCLAIMER_VERSION,
      }),
    }
  }

  // ── get_ack ──────────────────────────────────────────────────────────────────
  if (action === 'get_ack') {
    const { ok, data } = await supabaseQuery(
      `dossier_acknowledgments`,
      'GET',
      null,
      `?user_id=eq.${user.id}&is_current=eq.true&disclaimer_version=eq.${DISCLAIMER_VERSION}&limit=1`
    )

    const ack = Array.isArray(data) ? data[0] : null
    return {
      statusCode: 200,
      headers,
      body: JSON.stringify({
        acknowledged: !!ack,
        acknowledged_at: ack?.acknowledged_at || null,
        disclaimer_version: DISCLAIMER_VERSION,
      }),
    }
  }

  // ── save_review ──────────────────────────────────────────────────────────────
  if (action === 'save_review') {
    const { dossier_id, section_id, claim_text, status, note } = body
    if (!dossier_id || !section_id || !claim_text || !status) {
      return { statusCode: 400, headers, body: JSON.stringify({ error: 'Missing required fields' }) }
    }
    const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
    if (!UUID.test(dossier_id) || !UUID.test(section_id)) {
      return { statusCode: 400, headers, body: JSON.stringify({ error: 'Invalid dossier_id or section_id' }) }
    }

    const validStatuses = ['confirmed', 'rejected', 'needs_research']
    if (!validStatuses.includes(status)) {
      return { statusCode: 400, headers, body: JSON.stringify({ error: 'Invalid status' }) }
    }

    const claimKey = claim_text.slice(0, 100)

    // Try update first, then insert (upsert via unique index)
    const checkRes = await supabaseQuery(
      `dossier_claim_reviews`,
      'GET',
      null,
      `?dossier_id=eq.${encodeURIComponent(dossier_id)}&user_id=eq.${user.id}&section_id=eq.${encodeURIComponent(section_id)}&claim_text=like.${encodeURIComponent(claimKey + '*')}&limit=1`
    )

    const existing = Array.isArray(checkRes.data) ? checkRes.data[0] : null

    if (existing) {
      // Update existing
      await supabaseQuery(
        `dossier_claim_reviews?id=eq.${existing.id}`,
        'PATCH',
        { status, note: note || null, updated_at: new Date().toISOString() }
      )
      return { statusCode: 200, headers, body: JSON.stringify({ ok: true, id: existing.id }) }
    }

    // Insert new
    const { ok, data } = await supabaseQuery('dossier_claim_reviews', 'POST', {
      dossier_id,
      user_id:    user.id,
      section_id,
      claim_text: claim_text.slice(0, 500),
      status,
      note: note || null,
    })

    if (!ok) {
      return { statusCode: 500, headers, body: JSON.stringify({ error: 'Failed to save review' }) }
    }

    return { statusCode: 200, headers, body: JSON.stringify({ ok: true }) }
  }

  // ── get_reviews ──────────────────────────────────────────────────────────────
  if (action === 'get_reviews') {
    const { dossier_id } = body
    const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
    if (!dossier_id || !UUID_RE.test(dossier_id)) {
      return { statusCode: 400, headers, body: JSON.stringify({ error: 'valid dossier_id required' }) }
    }

    const { ok, data } = await supabaseQuery(
      `dossier_claim_reviews`,
      'GET',
      null,
      `?dossier_id=eq.${encodeURIComponent(dossier_id)}&user_id=eq.${user.id}&order=reviewed_at.desc`
    )

    return {
      statusCode: 200,
      headers,
      body: JSON.stringify({ ok: true, reviews: Array.isArray(data) ? data : [] }),
    }
  }

  return { statusCode: 400, headers, body: JSON.stringify({ error: 'Unknown action' }) }
}
