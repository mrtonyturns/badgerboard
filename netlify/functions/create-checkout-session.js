// netlify/functions/create-checkout-session.js
// Creates a Stripe Checkout session for a plan + bracket + billing-period combination.
//
// POST body: { plan, bracket?, billing, userId, email }
//   plan    — new keys: 'c_monitor' | 'c_active' | 'c_campaign' | 'a_monitor' | 'a_active' | 'a_campaign'
//             legacy:   'monitor' | 'campaign' | 'agency'  (still accepted)
//   bracket — required for action plans: 'b1' | 'b2_5' | 'b6' | 'b11' | 'b26' | 'b51'
//             NOT required for candidate plans (c_monitor, c_active, c_campaign)
//   billing — 'monthly' | 'quarterly' | 'semiannual' | 'annual'
//   userId  — Supabase user UUID
//   email   — user email (pre-fills Stripe checkout)
//
// Price IDs are baked in (not env vars) to stay under Lambda's 4KB env var limit.
// Run stripe-setup.mjs to regenerate if products are ever recreated.
//
// Also required env vars:
//   STRIPE_SECRET_KEY
//   SITE_URL  (e.g. https://www.badgerboardwi.com)

