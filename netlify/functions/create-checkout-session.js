const BILLING_SUFFIX = {
  monthly:    'M',
  quarterly:  'Q',
  semiannual: 'S',
  annual:     'A',
}

function sanitize(str, maxLen = 200) {
  if (str == null) return ''
  return String(str).replace(/[<>"'`]/g, '').slice(0, maxLen)
}

// Derive plan_type from plan key (mirrors server logic in admin-set-tier.js)
function planType(plan) {
  if (ACTION_PLANS.includes(plan) || LEGACY_PLANS.includes(plan)) return 'action'
  return 'candidate'
}

// Builds the env var name for the Stripe price ID.
// Candidate plans: STRIPE_PRICE_C_MONITOR_M
// Action plans:    STRIPE_PRICE_A_MONITOR_B2_5_M
// Legacy plans:    STRIPE_PRICE_MONITOR_B2_5_M  (old naming, backward compat)
function getPriceEnvKey(plan, bracket, billing) {
  const b = BILLING_SUFFIX[billing] || 'M'
  const planUpper = plan.toUpperCase()   // e.g. C_MONITOR, A_ACTIVE, MONITOR

  if (CANDIDATE_PLANS.includes(plan)) {
    // No bracket for candidate plans
    return `STRIPE_PRICE_${planUpper}_${b}`
  }
  // Action plans and legacy plans all use bracket
  const bracketUpper = (bracket || '').toUpperCase()  // e.g. B2_5, B6
  return `STRIPE_PRICE_${planUpper}_${bracketUpper}_${b}`
}

export const handler = async (event) => {
  if (event.httpMethod !== 'POST') {
    return { statusCode: 405, body: JSON.stringify({ error: 'Method not allowed' }) }
  }

  // Auth guard — require a valid Supabase JWT
  const authHeader = event.headers?.authorization || event.headers?.Authorization
  if (!authHeader?.startsWith('Bearer ')) {
    return { statusCode: 401, body: JSON.stringify({ error: 'Not authenticated' }) }
  }
  const authRes = await fetch(`${SUPABASE_URL}/auth/v1/user`, {
    headers: { apikey: SUPABASE_ANON, Authorization: authHeader },
  })
  if (!authRes.ok) {
    return { statusCode: 401, body: JSON.stringify({ error: 'Invalid or expired token' }) }
  }
  // Trust the verified token for identity — never the client-supplied userId.
  const authedUser = await authRes.json().catch(() => null)
  const authedUserId = authedUser?.id || null
  if (!authedUserId) {
    return { statusCode: 401, body: JSON.stringify({ error: 'Invalid or expired token' }) }
  }

  const stripe  = new Stripe(process.env.STRIPE_SECRET_KEY)
  const siteUrl = process.env.SITE_URL || 'https://www.badgerboardwi.com'

  let body
  try {
    body = JSON.parse(event.body || '{}')
  } catch {
    return { statusCode: 400, body: JSON.stringify({ error: 'Invalid JSON' }) }
  }

  const product = sanitize(body.product)
  const userId  = authedUserId  // use the authenticated user id, not body.userId
  const email   = sanitize(body.email, 320)

  // ── A la carte profile credit pack (one-time payment) ────────────────────────
  if (product === 'credits') {
    const pack = sanitize(body.pack)
    if (!VALID_CREDIT_PACKS.includes(pack)) {
      return { statusCode: 400, body: JSON.stringify({ error: `Invalid pack "${pack}". Must be one of: ${VALID_CREDIT_PACKS.join(', ')}` }) }
    }
    const envKey  = `STRIPE_PRICE_CREDITS_${pack.toUpperCase()}`
    const priceId = STRIPE_PRICES[envKey] || process.env[envKey]
    if (!priceId) {
      return {
        statusCode: 500,
        body: JSON.stringify({ error: `Price not configured. Add ${envKey} to your Netlify environment variables.` }),
      }
    }
    try {
      const session = await stripe.checkout.sessions.create({
        mode:                 'payment',
        payment_method_types: ['card'],
        line_items:           [{ price: priceId, quantity: 1 }],
        client_reference_id:  userId || undefined,
        customer_email:       email  || undefined,
        metadata:             { product: 'credits', pack, supabase_user_id: userId },
        success_url: `${siteUrl}/profiler?credits=success&pack=${pack}`,
        cancel_url:  `${siteUrl}/plans?credits=cancelled`,
        allow_promotion_codes: true,
      })
      console.log(`Credits checkout created: ${CREDIT_PACK_DISPLAY[pack]} for user ${userId}`)
      return { statusCode: 200, body: JSON.stringify({ url: session.url }) }
    } catch (err) {
      console.error('Stripe credits checkout error:', err.message)
      return { statusCode: 500, body: JSON.stringify({ error: 'An internal error occurred' }) }
    }
  }

  // ── Bulk action-plan credit pack (one-time payment) ───────────────────────────
  if (product === 'bulk_credits') {
    const pack = sanitize(body.pack)
    if (!VALID_BULK_CREDIT_PACKS.includes(pack)) {
      return { statusCode: 400, body: JSON.stringify({ error: `Invalid bulk pack "${pack}". Must be one of: ${VALID_BULK_CREDIT_PACKS.join(', ')}` }) }
    }
    const envKey  = `STRIPE_PRICE_BULK_CREDITS_${pack.toUpperCase()}`
    const priceId = STRIPE_PRICES[envKey] || process.env[envKey]
    if (!priceId) {
      return {
        statusCode: 500,
        body: JSON.stringify({ error: `Bulk credit price not configured. Add ${envKey} to your Netlify environment variables.` }),
      }
    }
    try {
      const session = await stripe.checkout.sessions.create({
        mode:                 'payment',
        payment_method_types: ['card'],
        line_items:           [{ price: priceId, quantity: 1 }],
        client_reference_id:  userId || undefined,
        customer_email:       email  || undefined,
        metadata:             { product: 'bulk_credits', pack, supabase_user_id: userId },
        success_url: `${siteUrl}/profiler?bulk_credits=success&pack=${pack}`,
        cancel_url:  `${siteUrl}/plans?bulk_credits=cancelled`,
        allow_promotion_codes: true,
      })
      console.log(`Bulk credits checkout created: ${BULK_CREDIT_PACK_DISPLAY[pack] || pack} for user ${userId}`)
      return { statusCode: 200, body: JSON.stringify({ url: session.url }) }
    } catch (err) {
      console.error('Stripe bulk credits checkout error:', err.message)
      return { statusCode: 500, body: JSON.stringify({ error: 'An internal error occurred' }) }
    }
  }

  // ── Subscription checkout ──────────────────────────────────────────────────
  const plan    = sanitize(body.plan)
  const bracket = sanitize(body.bracket)
  const billing = sanitize(body.billing) || 'monthly'

  // Validate plan
  if (!VALID_PLANS.includes(plan)) {
    return {
      statusCode: 400,
      body: JSON.stringify({ error: `Invalid plan "${plan}". Must be one of: ${VALID_PLANS.join(', ')}` }),
    }
  }

  // Validate billing period
  if (!VALID_BILLING.includes(billing)) {
    return {
      statusCode: 400,
      body: JSON.stringify({ error: `billing must be one of: ${VALID_BILLING.join(', ')}` }),
    }
  }

  // Bracket is required for action plans and legacy plans; optional for candidate plans
  const needsBracket = ACTION_PLANS.includes(plan) || LEGACY_PLANS.includes(plan)
  if (needsBracket) {
    if (!bracket || !VALID_BRACKETS.includes(bracket)) {
      return {
        statusCode: 400,
        body: JSON.stringify({ error: `bracket is required for ${plan} and must be one of: ${VALID_BRACKETS.join(', ')}` }),
      }
    }
  }

  const envKey  = getPriceEnvKey(plan, bracket || null, billing)
  const priceId = STRIPE_PRICES[envKey] || process.env[envKey]

  if (!priceId) {
    return {
      statusCode: 500,
      body: JSON.stringify({
        error: `Price not configured. Add ${envKey} to your Netlify environment variables (Stripe Dashboard → Products).`,
      }),
    }
  }

  const planLabel    = PLAN_DISPLAY[plan] || plan
  const bracketLabel = bracket ? (BRACKET_DISPLAY[bracket] || bracket) : ''
  const billingLabel = { monthly: 'Monthly', quarterly: 'Quarterly', semiannual: '6-Month', annual: 'Annual' }[billing] || billing
  const pt           = planType(plan)

  try {
    const session = await stripe.checkout.sessions.create({
      mode:                 'subscription',
      payment_method_types: ['card'],
      line_items:           [{ price: priceId, quantity: 1 }],

      client_reference_id: userId || undefined,
      customer_email:      email  || undefined,

      metadata: {
        plan,
        plan_type: pt,
        ...(bracket ? { bracket } : {}),
        billing,
        supabase_user_id: userId,
      },
      subscription_data: {
        metadata: {
          plan,
          plan_type: pt,
          ...(bracket ? { bracket } : {}),
          billing,
          supabase_user_id: userId,
        },
      },

      success_url: `${siteUrl}/settings?billing=success&plan=${plan}${bracket ? `&bracket=${bracket}` : ''}`,
      cancel_url:  `${siteUrl}/plans?billing=cancelled`,

      allow_promotion_codes: true,

      // Badger Board branding on the checkout page
      custom_text: {
        submit: {
          message: 'You\'ll be charged immediately. Cancel anytime from your account settings.',
        },
      },

      phone_number_collection: { enabled: false },
      billing_address_collection: 'auto',
    })

    console.log(`Checkout session created: ${planLabel}${bracketLabel ? ' / ' + bracketLabel : ''} / ${billingLabel} for user ${userId}`)

    return {
      statusCode: 200,
      body: JSON.stringify({ url: session.url }),
    }
  } catch (err) {
    console.error('Stripe checkout error:', err.message)
    return {
      statusCode: 500,
      body: JSON.stringify({ error: 'An internal error occurred' }),
    }
  }
}
